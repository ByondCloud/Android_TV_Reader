package com.cloud.androidtvreader.domain.model

/**
 * 书库里的一本书。
 *
 * ══ 它和 [ParsedBook] 的区别 —— 这个区分很重要 ══════════════════
 *   [ParsedBook] = "一次解析的【结果】"。它带着整本正文字符串，
 *                  是临时的、用完就丢的。
 *   Book         = "书库里的一条【记录】"。它只有元数据，体积很小，
 *                  可以被列表页一次加载几百条，也可以持久化到磁盘。
 *
 * 把这两个概念分开的实际好处：书架页不需要把每本书的正文都读进内存。
 * 等你书库里有 200 本书时，这个区别就是"秒开"和"卡 10 秒"的区别。
 * ═══════════════════════════════════════════════════════════════
 */
data class Book(
    /** 唯一标识，同时就是书籍目录名 */
    val id: String,
    val title: String,
    val author: String?,
    val format: BookFormat,
    /** 导入时探测到的编码名，例如 "GB18030"。排查乱码问题时必看 */
    val charsetName: String,
    /**
     * 用户导入时的原始文件名，界面上可以显示"来自 xxx.txt"。
     *
     * ══ 【它同时是查重的依据】══════════════════════════════════════
     * 导入时判断"这本书是不是已经在书架上了"，用的就是这个字段。
     *
     * 【为什么文件名就够，不需要内容哈希】
     * 因为扫描目录时【同一目录下文件名必然唯一】——
     * 这是文件系统本身的保证。所以"书库里有同名的来源文件"
     * 和"这个文件已经导入过了"是等价的。
     *
     * 用哈希（MD5/SHA）更"严谨"，但必须读完整本书才能算出来。
     * 而导入界面要在【扫描出列表的那一刻】就标出哪些已导入 ——
     * 那时去算哈希，书一多列表就要卡好几秒。
     * 文件名在扫描时就已经拿到了，代价是零。
     *
     * 【已知的行为】用户把同一个文件改名后再导入，会被当成一本新书。
     * 这其实是合理的 —— 用户主动改名，多半就是想要两份。
     * ═══════════════════════════════════════════════════════════════
     */
    val sourceFileName: String,
    /** 导入时间戳（毫秒） */
    val importedAt: Long,
    /** 阅读进度 */
    val progress: ReadingProgress,
) {
    /**
     * 书架卡片上的副标题，例如 "练习生 · 纯文本"。
     * listOfNotNull 会自动跳过 null 项，比手写 if-else 拼字符串干净。
     */
    val subtitle: String
        get() = listOfNotNull(author, format.displayName).joinToString(" · ")
}

/**
 * 阅读进度。
 *
 * ══ 核心设计：为什么是"第几章 + 章内第几个字符" ══════════════════
 *
 * 【为什么不用页码】
 * 因为页码会随字号、行距、屏幕尺寸变化。
 * 今天在 65 寸电视上"第 12 页"的那段内容，明天用户把字号调大一档，
 * 就变成"第 18 页"了。用页码存进度，用户改个字号就会丢失阅读位置 ——
 * 这是很多阅读器被吐槽"记不住进度"的根本原因。
 *
 * 【为什么字符偏移可以】
 * 字符偏移是【绝对坐标】，只和文本本身有关，不受显示方式影响。
 *
 * 【跨模式共享】
 * 翻页模式和滚动模式共用这一套坐标，所以两者互相切换时
 * 能精确停在同一个字上 —— 这是模块 6 的关键前提。
 *
 * 【为什么章内偏移而不是全文偏移】
 * 阅读器是"一章一章加载"的（章节是分页和渲染的基本单位）。
 * 章内偏移在一章内部自洽，将来章节重新切分时，
 * 也只有"跨章边界"那一点会受影响，而不是整本书的进度全乱。
 * ═══════════════════════════════════════════════════════════════
 */
data class ReadingProgress(
    /** 读到第几章（对应 [ParsedChapter.index]） */
    val chapterIndex: Int = 0,
    /** 章内字符偏移（相对于 [ParsedChapter.startOffset]） */
    val charOffset: Int = 0,
    /** 上次阅读时间戳（毫秒）。书架页用它来排"最近在读" */
    val updatedAt: Long = 0L,
) {
    /** 是否已经开始读过（全新的书 = 未开始） */
    val isStarted: Boolean get() = chapterIndex > 0 || charOffset > 0

    companion object {
        /** 全新导入的书用这个值 */
        val EMPTY = ReadingProgress()
    }
}
